# Server DNS: the resolvers this host itself uses. With systemd-resolved a
# drop-in sets global servers for every domain; with a plain /etc/resolv.conf
# the file is rewritten and a boot unit writes it again after DHCP. The original
# configuration is kept and restored exactly. resolvconf and NetworkManager
# hosts are reported, not changed.
GTM_SYSDNS_UNIT=gre-manager-resolv

gtm_sysdns_paths() {
    GTM_RESOLV=${GTM_RESOLV:-/etc/resolv.conf}
    GTM_RESOLVED_DIR=${GTM_RESOLVED_DIR:-/etc/systemd/resolved.conf.d}
    GTM_RESOLVED_UPSTREAM=${GTM_RESOLVED_UPSTREAM:-/run/systemd/resolve/resolv.conf}
    GTM_SYSDNS_DIR="$GTM_CONFIG_DIR/dns"
    GTM_SYSDNS_DROPIN="$GTM_RESOLVED_DIR/90-gre-manager.conf"
    GTM_SYSDNS_SCRIPT="${GTM_RUNTIME%/*}/resolv.sh"
    GTM_SYSDNS_SERVICE="$GTM_SERVICE_DIR/$GTM_SYSDNS_UNIT.service"
}

# A public resolver address: no loopback, unspecified, link-local or multicast.
gtm_sysdns_server() {
    local key
    if gtm_ipv4 "$1"; then [[ $1 != 0.* && $1 != 127.* && $1 != 169.254.* ]] && (( ${1%%.*} < 224 ))
    else
        gtm_ipv6 "$1" && gtm_key_of "$1" || return 1
        key=$GTM_KEY
        [[ $key != 0000000000000000000000000000000[01] && $key != ff* && $key != fe[89ab]* && $key != 00000000000000000000ffff* ]]
    fi
}

# resolved, file, resolvconf, networkmanager or unknown.
gtm_sysdns_mode() {
    local target
    gtm_sysdns_paths
    if [[ -L $GTM_RESOLV ]]; then
        target=$(readlink -f "$GTM_RESOLV" 2>/dev/null) || target=''
        case $target in
            */systemd/resolve/*) systemctl is-active --quiet systemd-resolved && { printf resolved; return; } ;;
            */resolvconf/*) printf resolvconf; return ;;
            */NetworkManager/*) printf networkmanager; return ;;
        esac
        printf unknown; return
    fi
    if [[ -f $GTM_RESOLV ]]; then
        if grep -q '^# Generated by NetworkManager' "$GTM_RESOLV" 2>/dev/null; then printf networkmanager; else printf file; fi
        return
    fi
    printf unknown
}

gtm_sysdns_nameservers() { [[ -r $1 ]] && awk '$1 == "nameserver" && NF >= 2 {print $2}' "$1" | head -n 8 | paste -sd' ' -; }

# Prints: mode, managed (0/1), current, upstream (resolved only), servers, original.
gtm_sysdns_status() {
    local mode managed=0 saved='' original=''
    mode=$(gtm_sysdns_mode)
    [[ -f $GTM_SYSDNS_DIR/servers ]] && { managed=1; saved=$(head -n 1 "$GTM_SYSDNS_DIR/servers"); }
    [[ -f $GTM_SYSDNS_DIR/resolv.conf.orig ]] && original=$(gtm_sysdns_nameservers "$GTM_SYSDNS_DIR/resolv.conf.orig")
    [[ -f $GTM_SYSDNS_DIR/original ]] && original=$(head -n 1 "$GTM_SYSDNS_DIR/original")
    printf 'mode\t%s\nmanaged\t%s\n' "$mode" "$managed"
    printf 'current\t%s\n' "$(gtm_sysdns_nameservers "$GTM_RESOLV")"
    [[ $mode != resolved ]] || printf 'upstream\t%s\n' "$(gtm_sysdns_nameservers "$GTM_RESOLVED_UPSTREAM")"
    printf 'servers\t%s\noriginal\t%s\n' "$saved" "$original"
}

# Renders a resolv.conf with SERVERS, keeping search/domain/options of BASE.
gtm_sysdns_resolv_render() {
    local base=$1 server; shift
    printf '# Managed by Traffic Manager (Optimization -> DNS). Restore there to undo.\n'
    for server in "$@"; do printf 'nameserver %s\n' "$server"; done
    [[ -r $base ]] && grep -E '^(search|domain|options)[[:space:]]' "$base" | head -n 6
    return 0
}

gtm_sysdns_apply() {
    local mode server tmp
    local -a servers=()
    (( $# >= 1 && $# <= 4 )) || { gtm_error 'Choose one to four DNS servers.'; return 2; }
    for server in "$@"; do
        gtm_sysdns_server "$server" || { gtm_error "Not a usable DNS server address: $server"; return 2; }
        [[ " ${servers[*]} " == *" $server "* ]] || servers+=("$server")
    done
    gtm_root || return 1
    mode=$(gtm_sysdns_mode)
    mkdir -p "$GTM_SYSDNS_DIR" && chmod 700 "$GTM_SYSDNS_DIR" || return 1
    case $mode in
        resolved)
            [[ -f $GTM_SYSDNS_DIR/original ]] || gtm_sysdns_nameservers "$GTM_RESOLVED_UPSTREAM" > "$GTM_SYSDNS_DIR/original" || return 1
            mkdir -p "$GTM_RESOLVED_DIR" || return 1
            tmp=$(mktemp "$GTM_SYSDNS_DROPIN.XXXXXX") || return 1
            # "~." routes every domain to these servers ahead of DHCP-provided ones.
            printf '# Managed by Traffic Manager (Optimization -> DNS).\n[Resolve]\nDNS=%s\nDomains=~.\n' "${servers[*]}" > "$tmp" &&
                chmod 644 "$tmp" && mv "$tmp" "$GTM_SYSDNS_DROPIN" || { rm -f "$tmp"; return 1; }
            systemctl restart systemd-resolved || return 1 ;;
        file)
            [[ -f $GTM_SYSDNS_DIR/resolv.conf.orig ]] || cp -p "$GTM_RESOLV" "$GTM_SYSDNS_DIR/resolv.conf.orig" || return 1
            gtm_sysdns_publish "${servers[@]}" || return 1 ;;
        resolvconf|networkmanager) gtm_error "DNS on this server is managed by $mode; change it there."; return 1 ;;
        *) gtm_error 'Unknown resolver setup; DNS was not changed.'; return 1 ;;
    esac
    printf '%s\n' "${servers[*]}" > "$GTM_SYSDNS_DIR/servers" && chmod 600 "$GTM_SYSDNS_DIR/servers" || return 1
    printf 'DNS servers set to %s (%s).\n' "${servers[*]}" "$mode"
}

# Writes resolv.conf and a boot unit that writes it again after the network
# (DHCP clients may replace the file at boot).
gtm_sysdns_publish() {
    local tmp script
    tmp=$(mktemp "$GTM_RESOLV.XXXXXX") || return 1
    gtm_sysdns_resolv_render "$GTM_SYSDNS_DIR/resolv.conf.orig" "$@" > "$tmp" && chmod 644 "$tmp" && mv "$tmp" "$GTM_RESOLV" || { rm -f "$tmp"; return 1; }
    mkdir -p "${GTM_SYSDNS_SCRIPT%/*}" || return 1
    script=$(mktemp "$GTM_SYSDNS_SCRIPT.XXXXXX") || return 1
    {
        printf '#!/bin/sh\n# Generated by Traffic Manager: server DNS after boot.\n'
        printf '[ -L %s ] && exit 0\n' "$GTM_RESOLV"
        printf "cat > %s.gtm <<'GTM_EOF'\n" "$GTM_RESOLV"
        gtm_sysdns_resolv_render "$GTM_SYSDNS_DIR/resolv.conf.orig" "$@"
        printf 'GTM_EOF\nchmod 644 %s.gtm && mv %s.gtm %s\n' "$GTM_RESOLV" "$GTM_RESOLV" "$GTM_RESOLV"
    } > "$script" && chmod 700 "$script" && mv "$script" "$GTM_SYSDNS_SCRIPT" || { rm -f "$script"; return 1; }
    cat > "$GTM_SYSDNS_SERVICE" <<EOF
[Unit]
Description=Traffic Manager server DNS
Wants=network-online.target
After=network-online.target
[Service]
Type=oneshot
ExecStart=/bin/sh $GTM_SYSDNS_SCRIPT
[Install]
WantedBy=multi-user.target
EOF
    systemctl daemon-reload && systemctl enable "$GTM_SYSDNS_UNIT.service" >/dev/null
}

gtm_sysdns_restore() {
    local tmp
    gtm_root || return 1
    [[ -f $GTM_SYSDNS_DIR/servers ]] || { printf 'DNS is not managed here; nothing to restore.\n'; return 0; }
    if [[ -e $GTM_SYSDNS_DROPIN ]]; then
        rm -f "$GTM_SYSDNS_DROPIN" && systemctl restart systemd-resolved || return 1
    fi
    if [[ -e $GTM_SYSDNS_SERVICE ]]; then
        systemctl disable "$GTM_SYSDNS_UNIT.service" >/dev/null 2>&1 || true
        rm -f "$GTM_SYSDNS_SERVICE" "$GTM_SYSDNS_SCRIPT" && systemctl daemon-reload || return 1
    fi
    if [[ -f $GTM_SYSDNS_DIR/resolv.conf.orig && ! -L $GTM_RESOLV ]]; then
        tmp=$(mktemp "$GTM_RESOLV.XXXXXX") || return 1
        cp -p "$GTM_SYSDNS_DIR/resolv.conf.orig" "$tmp" && mv "$tmp" "$GTM_RESOLV" || { rm -f "$tmp"; return 1; }
    fi
    rm -f "$GTM_SYSDNS_DIR/servers" "$GTM_SYSDNS_DIR/original" "$GTM_SYSDNS_DIR/resolv.conf.orig" || return 1
    printf 'Original DNS configuration restored.\n'
}

