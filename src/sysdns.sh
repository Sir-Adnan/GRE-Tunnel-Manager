# Server DNS: the resolvers this host itself uses. With systemd-resolved a
# drop-in sets global servers for every domain; with a plain /etc/resolv.conf
# the file is rewritten and a boot unit writes it again after DHCP. The original
# configuration is kept and restored exactly. resolvconf and NetworkManager
# hosts are reported, not changed.
GTM_SYSDNS_UNIT=gre-manager-resolv

gtm_sysdns_paths() {
    GTM_RESOLV=${GTM_RESOLV:-/etc/resolv.conf}
    GTM_RESOLVED_DIR=${GTM_RESOLVED_DIR:-/etc/systemd/resolved.conf.d}
    GTM_RESOLVED_UPSTREAM=${GTM_RESOLVED_UPSTREAM:-/run/systemd/resolve/resolv.conf}
    GTM_SYSDNS_DIR="$GTM_CONFIG_DIR/dns"
    # resolved reads drop-ins in file-name order across /etc, /run and /usr/lib
    # and the last list assignment wins. "zz-" sorts after numbered and named
    # drop-ins (dns.conf, adguardhome.conf), so our reset and servers apply.
    GTM_SYSDNS_DROPIN="$GTM_RESOLVED_DIR/zz-gre-manager.conf"
    # Releases before 1.5.3 wrote 90-gre-manager.conf; it is migrated on apply.
    GTM_SYSDNS_LEGACY_DROPIN="$GTM_RESOLVED_DIR/90-gre-manager.conf"
    GTM_SYSDNS_SCRIPT="${GTM_RUNTIME%/*}/resolv.sh"
    GTM_SYSDNS_SERVICE="$GTM_SERVICE_DIR/$GTM_SYSDNS_UNIT.service"
}

# A public resolver address: no loopback, unspecified, link-local or multicast.
gtm_sysdns_server() {
    local key
    if gtm_ipv4 "$1"; then [[ $1 != 0.* && $1 != 127.* && $1 != 169.254.* ]] && (( ${1%%.*} < 224 ))
    else
        gtm_ipv6 "$1" && gtm_key_of "$1" || return 1
        key=$GTM_KEY
        [[ $key != 0000000000000000000000000000000[01] && $key != ff* && $key != fe[89ab]* && $key != 00000000000000000000ffff* ]]
    fi
}

# resolved, file, resolvconf, networkmanager or unknown.
gtm_sysdns_mode() {
    local target
    gtm_sysdns_paths
    if [[ -L $GTM_RESOLV ]]; then
        target=$(readlink -f "$GTM_RESOLV" 2>/dev/null) || target=''
        case $target in
            */systemd/resolve/*) systemctl is-active --quiet systemd-resolved && { printf resolved; return; } ;;
            */resolvconf/*) printf resolvconf; return ;;
            */NetworkManager/*) printf networkmanager; return ;;
        esac
        printf unknown; return
    fi
    if [[ -f $GTM_RESOLV ]]; then
        if grep -q '^# Generated by NetworkManager' "$GTM_RESOLV" 2>/dev/null; then printf networkmanager; else printf file; fi
        return
    fi
    printf unknown
}

gtm_sysdns_nameservers() { [[ -r $1 ]] && awk '$1 == "nameserver" && NF >= 2 {print $2}' "$1" | head -n 8 | paste -sd' ' -; }

gtm_sysdns_resolved_query() {
    command -v resolvectl >/dev/null 2>&1 || return 2
    local output
    output=$(LC_ALL=C timeout 3 resolvectl dns 2>/dev/null) || return 1
    awk '$1 == "Global:" {$1=""; sub(/^ /, ""); print; found=1; exit} END {if (!found) exit 1}' <<< "$output"
}

# Drop-ins that set DNS= and sort after ours (they would override it).
gtm_sysdns_later_dropins() {
    local dir file name ours=${GTM_SYSDNS_DROPIN##*/} LC_ALL=C
    for dir in "$GTM_RESOLVED_DIR" /run/systemd/resolved.conf.d /usr/local/lib/systemd/resolved.conf.d /usr/lib/systemd/resolved.conf.d; do
        for file in "$dir"/*.conf; do
            [[ -f $file ]] || continue
            name=${file##*/}
            [[ $name != "$ours" && $name > $ours ]] || continue
            grep -Eq '^[[:space:]]*DNS[[:space:]]*=' "$file" 2>/dev/null && printf '%s\n' "$file"
        done
    done
}

gtm_sysdns_resolved_verify() {
    local actual='' status address key wanted='' observed='' attempt later
    for address in "$@"; do key=$(gtm_ip_key "$address") || return 1; wanted+="$key"$'\n'; done
    wanted=$(sort -u <<< "$wanted")
    # resolved can report the previous list for a moment after a restart.
    for attempt in 1 2 3 4 5; do
        actual=$(gtm_sysdns_resolved_query); status=$?
        ((status != 2)) || return 0 # Older hosts may not ship the optional status CLI.
        if ((status == 0)); then
            observed=''
            for address in $actual; do
                # Newer releases may print a port, interface or TLS name.
                address=${address%%#*}; address=${address%%%*}
                [[ $address =~ ^\[(.*)\](:[0-9]+)?$ ]] && address=${BASH_REMATCH[1]}
                [[ $address == *.*:* ]] && address=${address%:*}
                key=$(gtm_ip_key "$address") || continue
                observed+="$key"$'\n'
            done
            [[ $(sort -u <<< "$observed") != "$wanted" ]] || return 0
        fi
        ((attempt == 5)) || sleep "${GTM_SYSDNS_SETTLE:-1}"
    done
    ((status == 0)) || { gtm_error 'Could not verify the active global DNS settings.'; return 1; }
    later=$(gtm_sysdns_later_dropins | paste -sd' ' -)
    gtm_error "The resolver reports global DNS '${actual:-none}' instead of the selected servers.${later:+ Later drop-ins override it: $later.}"
    return 1
}

# Prints: mode, managed (0/1), current, upstream (resolved only), servers, original.
gtm_sysdns_status() {
    local mode managed=0 saved='' original='' active=''
    gtm_sysdns_paths
    mode=$(gtm_sysdns_mode)
    [[ -f $GTM_SYSDNS_DIR/servers ]] && { managed=1; saved=$(head -n 1 "$GTM_SYSDNS_DIR/servers"); }
    [[ -f $GTM_SYSDNS_DIR/resolv.conf.orig ]] && original=$(gtm_sysdns_nameservers "$GTM_SYSDNS_DIR/resolv.conf.orig")
    [[ -f $GTM_SYSDNS_DIR/original ]] && original=$(head -n 1 "$GTM_SYSDNS_DIR/original")
    printf 'mode\t%s\nmanaged\t%s\n' "$mode" "$managed"
    printf 'current\t%s\n' "$(gtm_sysdns_nameservers "$GTM_RESOLV")"
    [[ $mode != resolved ]] || printf 'upstream\t%s\n' "$(gtm_sysdns_nameservers "$GTM_RESOLVED_UPSTREAM")"
    if [[ $mode == resolved ]]; then
        active=$(gtm_sysdns_resolved_query) || active=''
    elif [[ $mode == file ]]; then active=$(gtm_sysdns_nameservers "$GTM_RESOLV"); fi
    printf 'active\t%s\n' "$active"
    printf 'servers\t%s\noriginal\t%s\n' "$saved" "$original"
}

# Renders a resolv.conf with SERVERS, keeping search/domain/options of BASE.
gtm_sysdns_resolv_render() {
    local base=$1 server; shift
    printf '# Managed by Traffic Manager (Optimization -> DNS). Restore there to undo.\n'
    for server in "$@"; do printf 'nameserver %s\n' "$server"; done
    [[ -r $base ]] && grep -E '^(search|domain|options)[[:space:]]' "$base" | head -n 6
    return 0
}

gtm_sysdns_apply_checked() {
    local mode server tmp
    local -a servers=()
    (( $# >= 1 && $# <= 4 )) || { gtm_error 'Choose one to four DNS servers.'; return 2; }
    for server in "$@"; do
        gtm_sysdns_server "$server" || { gtm_error "Not a usable DNS server address: $server"; return 2; }
        [[ " ${servers[*]} " == *" $server "* ]] || servers+=("$server")
    done
    gtm_root || return 1
    mode=$(gtm_sysdns_mode)
    mkdir -p "$GTM_SYSDNS_DIR" && chmod 700 "$GTM_SYSDNS_DIR" || return 1
    case $mode in
        resolved)
            [[ -f $GTM_SYSDNS_DIR/original ]] || gtm_sysdns_nameservers "$GTM_RESOLVED_UPSTREAM" > "$GTM_SYSDNS_DIR/original" || return 1
            mkdir -p "$GTM_RESOLVED_DIR" || return 1
            # An earlier release's managed drop-in is ours; replace it here.
            if [[ -f $GTM_SYSDNS_LEGACY_DROPIN && -f $GTM_SYSDNS_DIR/servers ]] && grep -q '^# Managed by Traffic Manager' "$GTM_SYSDNS_LEGACY_DROPIN"; then
                rm -f "$GTM_SYSDNS_LEGACY_DROPIN" || return 1
            fi
            if [[ ! -f $GTM_SYSDNS_DIR/resolved.conf.present ]]; then
                if [[ -f $GTM_SYSDNS_DROPIN && ! -f $GTM_SYSDNS_DIR/servers ]]; then
                    cp -p "$GTM_SYSDNS_DROPIN" "$GTM_SYSDNS_DIR/resolved.conf.orig" && printf '1\n' > "$GTM_SYSDNS_DIR/resolved.conf.present" || return 1
                else printf '0\n' > "$GTM_SYSDNS_DIR/resolved.conf.present" || return 1; fi
            fi
            tmp=$(mktemp "$GTM_SYSDNS_DROPIN.XXXXXX") || return 1
            # "~." routes every domain to these servers ahead of DHCP-provided ones.
            # List settings accumulate across drop-ins unless explicitly reset.
            printf '# Managed by Traffic Manager (Optimization -> DNS).\n[Resolve]\nDNS=\nDNS=%s\nFallbackDNS=\nDomains=\nDomains=~.\n' "${servers[*]}" > "$tmp" &&
                chmod 644 "$tmp" && mv "$tmp" "$GTM_SYSDNS_DROPIN" || { rm -f "$tmp"; return 1; }
            systemctl restart systemd-resolved && gtm_sysdns_resolved_verify "${servers[@]}" || return 1 ;;
        file)
            [[ -f $GTM_SYSDNS_DIR/resolv.conf.orig ]] || cp -p "$GTM_RESOLV" "$GTM_SYSDNS_DIR/resolv.conf.orig" || return 1
            gtm_sysdns_publish "${servers[@]}" || return 1 ;;
        resolvconf|networkmanager) gtm_error "DNS on this server is managed by $mode; change it there."; return 1 ;;
        *) gtm_error 'Unknown resolver setup; DNS was not changed.'; return 1 ;;
    esac
    printf '%s\n' "${servers[*]}" > "$GTM_SYSDNS_DIR/servers" && chmod 600 "$GTM_SYSDNS_DIR/servers" || return 1
    printf 'DNS servers set to %s (%s).\n' "${servers[*]}" "$mode"
}

# Writes resolv.conf and a boot unit that writes it again after the network
# (DHCP clients may replace the file at boot).
gtm_sysdns_publish() {
    local tmp script
    tmp=$(mktemp "$GTM_RESOLV.XXXXXX") || return 1
    gtm_sysdns_resolv_render "$GTM_SYSDNS_DIR/resolv.conf.orig" "$@" > "$tmp" && chmod 644 "$tmp" && mv "$tmp" "$GTM_RESOLV" || { rm -f "$tmp"; return 1; }
    mkdir -p "${GTM_SYSDNS_SCRIPT%/*}" || return 1
    script=$(mktemp "$GTM_SYSDNS_SCRIPT.XXXXXX") || return 1
    {
        printf '#!/bin/sh\n# Generated by Traffic Manager: server DNS after boot.\n'
        printf '[ -L %s ] && exit 0\n' "$GTM_RESOLV"
        printf "cat > %s.gtm <<'GTM_EOF'\n" "$GTM_RESOLV"
        gtm_sysdns_resolv_render "$GTM_SYSDNS_DIR/resolv.conf.orig" "$@"
        printf 'GTM_EOF\nchmod 644 %s.gtm && mv %s.gtm %s\n' "$GTM_RESOLV" "$GTM_RESOLV" "$GTM_RESOLV"
    } > "$script" && chmod 700 "$script" && mv "$script" "$GTM_SYSDNS_SCRIPT" || { rm -f "$script"; return 1; }
    cat > "$GTM_SYSDNS_SERVICE" <<EOF
[Unit]
Description=Traffic Manager server DNS
Wants=network-online.target
After=network-online.target
[Service]
Type=oneshot
ExecStart=/bin/sh $GTM_SYSDNS_SCRIPT
[Install]
WantedBy=multi-user.target
EOF
    systemctl daemon-reload && systemctl enable "$GTM_SYSDNS_UNIT.service" >/dev/null
}

gtm_sysdns_restore_checked() {
    local tmp
    gtm_root || return 1
    [[ -f $GTM_SYSDNS_DIR/servers ]] || { printf 'DNS is not managed here; nothing to restore.\n'; return 0; }
    if [[ -f $GTM_SYSDNS_LEGACY_DROPIN ]] && grep -q '^# Managed by Traffic Manager' "$GTM_SYSDNS_LEGACY_DROPIN"; then
        rm -f "$GTM_SYSDNS_LEGACY_DROPIN" || return 1
        [[ -e $GTM_SYSDNS_DROPIN ]] || systemctl restart systemd-resolved || return 1
    fi
    if [[ -e $GTM_SYSDNS_DROPIN ]]; then
        if [[ -f $GTM_SYSDNS_DIR/resolved.conf.orig ]]; then
            cp -p "$GTM_SYSDNS_DIR/resolved.conf.orig" "$GTM_SYSDNS_DROPIN" || return 1
        else rm -f "$GTM_SYSDNS_DROPIN" || return 1; fi
        systemctl restart systemd-resolved || return 1
    fi
    if [[ -e $GTM_SYSDNS_SERVICE ]]; then
        systemctl disable "$GTM_SYSDNS_UNIT.service" >/dev/null 2>&1 || true
        rm -f "$GTM_SYSDNS_SERVICE" "$GTM_SYSDNS_SCRIPT" && systemctl daemon-reload || return 1
    fi
    if [[ -f $GTM_SYSDNS_DIR/resolv.conf.orig && ! -L $GTM_RESOLV ]]; then
        tmp=$(mktemp "$GTM_RESOLV.XXXXXX") || return 1
        cp -p "$GTM_SYSDNS_DIR/resolv.conf.orig" "$tmp" && mv "$tmp" "$GTM_RESOLV" || { rm -f "$tmp"; return 1; }
    fi
    rm -f "$GTM_SYSDNS_DIR/servers" "$GTM_SYSDNS_DIR/original" "$GTM_SYSDNS_DIR/resolv.conf.orig" "$GTM_SYSDNS_DIR/resolved.conf.orig" "$GTM_SYSDNS_DIR/resolved.conf.present" || return 1
    printf 'Original DNS configuration restored.\n'
}

# Capture only the exact files owned by this operation. A failed restart or boot
# unit publication restores the configuration from immediately before the request.
gtm_sysdns_transaction() {
    local operation=$1 stage file index mode had_service=0 enabled=0 result recovery=0
    shift
    gtm_root || return 1
    gtm_sysdns_paths
    mode=$(gtm_sysdns_mode)
    for file in "$GTM_SYSDNS_DIR" "$GTM_RESOLVED_DIR" "${GTM_SYSDNS_SCRIPT%/*}" "$GTM_SERVICE_DIR"; do
        [[ ! -L $file && ( ! -e $file || -d $file ) ]] || { gtm_error "Unsafe DNS directory: $file"; return 1; }
    done
    local -a files=("$GTM_SYSDNS_DROPIN" "$GTM_SYSDNS_LEGACY_DROPIN" "$GTM_SYSDNS_SCRIPT" "$GTM_SYSDNS_SERVICE" "$GTM_SYSDNS_DIR/servers" "$GTM_SYSDNS_DIR/original" "$GTM_SYSDNS_DIR/resolv.conf.orig" "$GTM_SYSDNS_DIR/resolved.conf.orig" "$GTM_SYSDNS_DIR/resolved.conf.present")
    [[ $mode != file ]] || files+=("$GTM_RESOLV")
    [[ ! -f $GTM_SYSDNS_SERVICE ]] || { had_service=1; systemctl is-enabled --quiet "$GTM_SYSDNS_UNIT.service" && enabled=1; }
    stage=$(mktemp -d "$GTM_RUN_DIR/sysdns.XXXXXX") || return 1
    chmod 700 "$stage" || return 1
    for index in "${!files[@]}"; do
        file=${files[$index]}
        if [[ -L $file || ( -e $file && ! -f $file ) ]]; then gtm_error "Unsafe DNS artifact: $file"; rmdir "$stage" 2>/dev/null || true; return 1; fi
        [[ ! -f $file ]] || cp -p "$file" "$stage/$index" || return 1
    done
    case $operation in
        apply) gtm_sysdns_apply_checked "$@"; result=$?;;
        restore) gtm_sysdns_restore_checked; result=$?;;
        *) return 2;;
    esac
    if ((result)); then
        for index in "${!files[@]}"; do
            file=${files[$index]}
            if [[ -f $stage/$index ]]; then cp -p "$stage/$index" "$file" || recovery=1
            else rm -f -- "$file" || recovery=1; fi
        done
        if [[ $mode == resolved ]]; then systemctl restart systemd-resolved || recovery=1; fi
        if ((had_service)); then
            systemctl daemon-reload || recovery=1
            if ((enabled)); then systemctl enable "$GTM_SYSDNS_UNIT.service" >/dev/null || recovery=1; fi
        else systemctl disable "$GTM_SYSDNS_UNIT.service" >/dev/null 2>&1 || true; systemctl daemon-reload || recovery=1; fi
        gtm_error 'DNS change failed; the previous configuration was restored.'
        ((recovery == 0)) || gtm_error 'DNS recovery needs attention; inspect the resolver service.'
    fi
    for index in "${!files[@]}"; do rm -f -- "$stage/$index" || return 1; done
    rmdir "$stage" || return 1
    return "$result"
}

gtm_sysdns_apply() { gtm_sysdns_transaction apply "$@"; }
gtm_sysdns_restore() { gtm_sysdns_transaction restore; }

