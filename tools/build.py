#!/usr/bin/env python3
"""Build the standalone release from ordered Bash modules (stdlib only)."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = ('core', 'server_info', 'ui', 'haproxy_routing', 'haproxy', 'realm_options', 'metadata', 'state', 'firewall', 'components', 'relays', 'transports', 'rathole', 'catalog', 'inspect', 'forms', 'optimize', 'cleanup', 'links', 'reverse_api', 'pair_api', 'recovery', 'history', 'diagnose', 'api', 'panel', 'menus')


# GTM_VERSION in src/core.sh is the release number. These copies must match it;
# each pattern captures the version in one file that cannot import the others.
VERSION_COPIES = (
    ('panel/internal/version/version.go', r'^const Number = "([^"]+)"$'),
    ('panel/web/src/lib/version.ts', r'^export const panelVersion = "([^"]+)";$'),
    ('panel/web/package.json', r'^  "version": "([^"]+)",$'),
    ('panel-install.sh', r'^PANEL_VERSION=(\S+)$'),
    ('node-install.sh', r'^NODE_VERSION=(\S+)$'),
)


def release_version():
    core = (ROOT / 'src' / 'core.sh').read_text(encoding='utf-8')
    version = re.search(r'^GTM_VERSION=((?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*))$', core, re.M)
    if not version:
        raise ValueError('src/core.sh must define GTM_VERSION as MAJOR.MINOR.PATCH')
    return version[1]


def version_mismatches(version):
    problems = []
    for path, pattern in VERSION_COPIES:
        found = re.findall(pattern, (ROOT / path).read_text(encoding='utf-8'), re.M)
        if found != [version]:
            problems.append(f'{path}: expected {version}, found {", ".join(found) or "nothing"}')
    return problems


def build():
    version = release_version()
    parts = [f'#!/usr/bin/env bash\n# GRE / Traffic Manager v{version}\n'
             '# Generated by tools/build.py. Edit src/*.sh, then rebuild.\n'
             '# gre-stable.sh is a separate, frozen legacy release.\n']
    for name in MODULES:
        parts.append('\n# BEGIN MODULE: ' + name + '\n')
        parts.append((ROOT / 'src' / (name + '.sh')).read_text(encoding='utf-8').rstrip() + '\n')
    parts.append('\nif [[ ${BASH_SOURCE[0]} == "$0" ]]; then\n    gtm_main "$@"\nfi\n')
    return ''.join(parts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = build()
    target = ROOT / 'gre.sh'
    if args.check:
        mismatches = version_mismatches(release_version())
        if mismatches:
            raise SystemExit('Version copies differ from src/core.sh:\n  ' + '\n  '.join(mismatches))
        raise SystemExit(0 if target.read_text(encoding='utf-8') == result else 'gre.sh needs rebuilding')
    target.write_text(result, encoding='utf-8', newline='\n')
