#!/usr/bin/env python3
"""Collect license texts of the Go modules linked into gtm-panel.

Writes panel/LICENSES/GoDependencies.txt (shipped in release packages).
Run after changing panel/go.mod:  python3 tools/go_licenses.py
With --check it only reports whether the file is current (needs Go).
"""
import argparse
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'panel' / 'LICENSES' / 'GoDependencies.txt'
NAMES = ('LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'COPYING')


def linked_modules():
    out = subprocess.run(
        ['go', 'list', '-deps', '-f', '{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}', './cmd/gtm-panel'],
        cwd=ROOT / 'panel', check=True, capture_output=True, text=True).stdout
    return sorted({tuple(line.split('\t')) for line in out.splitlines() if line})


def render():
    parts = ['Go modules linked into gtm-panel, with their license texts.\n'
             'Generated by tools/go_licenses.py from panel/go.mod and go.sum.\n']
    for path, version, directory in linked_modules():
        license_file = next((Path(directory) / n for n in NAMES if (Path(directory) / n).is_file()), None)
        if license_file is None:
            raise SystemExit(f'no license file found for {path} {version}')
        text = license_file.read_text(encoding='utf-8', errors='replace').strip()
        parts.append(f'\n===== {path} {version} =====\n\n{license_file.name}\n{text}\n')
    return ''.join(parts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        current = TARGET.read_text(encoding='utf-8') if TARGET.exists() else ''
        raise SystemExit(0 if current == content else 'panel/LICENSES/GoDependencies.txt is out of date; run tools/go_licenses.py')
    TARGET.write_text(content, encoding='utf-8', newline='\n')
    print(f'wrote {TARGET.relative_to(ROOT)}')
